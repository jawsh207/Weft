#!/usr/bin/env python3
"""
Extract US → British / Canadian / Australian spelling differences from the
English Speller Database (ESDB, formerly SCOWL; https://github.com/en-wl/wordlist)
into sources/en_variants.tsv, which build_dict.py uses to turn the en_US
dictionary into en_GB, en_CA and en_AU ones.

    git clone https://github.com/en-wl/wordlist && (cd wordlist && make)
    python3 tools/dictgen/make_variants.py wordlist/scowl.db

Output columns (tab separated):
  region   GB, CA or AU
  us       the American spelling ("color")
  variant  the region's preferred spelling ("colour")
  level    how acceptable the US spelling still is in the region:
           0-4 common or equal, 5-6 a known variant, 9 not used
  keep     1 if the US spelling is also a preferred word in the region in
           another sense ("tire" = to get tired is fine in GB; "tyre" is the wheel)

The output is committed, so building dictionaries doesn't need ESDB.
ESDB: Copyright 2000-2026 Kevin Atkinson, MIT-like license (see
sources/LICENSE-ESDB.txt).
"""

from __future__ import annotations

import sqlite3
import sys
from collections import defaultdict
from pathlib import Path

REGIONS = {"GB": "B", "CA": "C", "AU": "D"}  # GB: the common -ise spelling
OUT = Path(__file__).resolve().parent / "sources" / "en_variants.tsv"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    db = sqlite3.connect(sys.argv[1])
    # (group, pos) → [(word, spelling, level)]
    forms: dict[tuple[int, str], list[tuple[str, str, int]]] = defaultdict(list)
    for group, pos, word, spelling, level in db.execute(
        "select group_id, pos, word, spelling, variant_level from words_w_variant_info "
        "where spelling in ('A','B','C','D')"
    ):
        if " " in word or "." in word:
            continue
        forms[(group, pos)].append((word, spelling, level))

    rows = set()
    for region, sp in REGIONS.items():
        preferred_anywhere = {w for fs in forms.values() for (w, s, lv) in fs if s == sp and lv == 0}
        mapping: dict[str, tuple[str, int]] = {}
        for fs in forms.values():
            us = sorted({w for (w, s, lv) in fs if s == "A" and lv == 0})
            here = sorted({w for (w, s, lv) in fs if s == sp and lv == 0})
            if not us or not here:
                continue
            for u in us:
                if u in here:
                    continue
                v = here[0]
                level = min((lv for (w, s, lv) in fs if w == u and s == sp), default=9)
                old = mapping.get(u)
                if old is None or level < old[1]:
                    mapping[u] = (v, level)
        for u, (v, level) in mapping.items():
            if u == v or u.lower() == v.lower():
                continue
            keep = 1 if u in preferred_anywhere else 0
            rows.add((region, u, v, level, keep))

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("# region\tus\tvariant\tlevel\tkeep  (generated by make_variants.py from ESDB; see LICENSE-ESDB.txt)\n")
        for r in sorted(rows):
            f.write("\t".join(map(str, r)) + "\n")
    by = defaultdict(int)
    for r in rows:
        by[r[0]] += 1
    print(f"Wrote {OUT}: " + ", ".join(f"{k} {v:,}" for k, v in sorted(by.items())))


if __name__ == "__main__":
    main()
